CREATE TABLE technician_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL UNIQUE,
    active BOOLEAN NOT NULL DEFAULT FALSE,
    service_area VARCHAR(160),
    availability VARCHAR(24) NOT NULL DEFAULT 'NOT_CONFIGURED',
    capacity_limit INTEGER NOT NULL DEFAULT 3,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_technician_profiles_account
        FOREIGN KEY (account_id) REFERENCES customer_accounts (id) ON DELETE RESTRICT,
    CONSTRAINT ck_technician_profiles_availability
        CHECK (availability IN ('NOT_CONFIGURED', 'AVAILABLE', 'UNAVAILABLE')),
    CONSTRAINT ck_technician_profiles_capacity
        CHECK (capacity_limit BETWEEN 1 AND 20)
);

CREATE TABLE technician_service_modes (
    technician_profile_id BIGINT NOT NULL,
    service_mode VARCHAR(24) NOT NULL,
    CONSTRAINT pk_technician_service_modes PRIMARY KEY (technician_profile_id, service_mode),
    CONSTRAINT fk_technician_service_modes_profile
        FOREIGN KEY (technician_profile_id) REFERENCES technician_profiles (id) ON DELETE CASCADE,
    CONSTRAINT ck_technician_service_modes_value
        CHECK (service_mode IN ('HOME_VISIT', 'REPAIR_CENTRE'))
);

CREATE TABLE technician_skills (
    technician_profile_id BIGINT NOT NULL,
    repair_service_id BIGINT NOT NULL,
    CONSTRAINT pk_technician_skills PRIMARY KEY (technician_profile_id, repair_service_id),
    CONSTRAINT fk_technician_skills_profile
        FOREIGN KEY (technician_profile_id) REFERENCES technician_profiles (id) ON DELETE CASCADE,
    CONSTRAINT fk_technician_skills_service
        FOREIGN KEY (repair_service_id) REFERENCES repair_services (id) ON DELETE RESTRICT
);

CREATE INDEX idx_technician_profiles_active_availability
    ON technician_profiles (active, availability);

CREATE INDEX idx_technician_skills_service
    ON technician_skills (repair_service_id);

CREATE TABLE supplier_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL UNIQUE,
    business_name VARCHAR(160) NOT NULL,
    contact_email VARCHAR(254),
    active BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_supplier_profiles_account
        FOREIGN KEY (account_id) REFERENCES customer_accounts (id) ON DELETE RESTRICT,
    CONSTRAINT ck_supplier_profiles_business_name
        CHECK (btrim(business_name) <> ''),
    CONSTRAINT ck_supplier_profiles_contact_email
        CHECK (contact_email IS NULL OR contact_email = lower(btrim(contact_email)))
);

CREATE INDEX idx_supplier_profiles_active
    ON supplier_profiles (active);
