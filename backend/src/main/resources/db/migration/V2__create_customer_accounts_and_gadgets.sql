CREATE TABLE customer_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(120) NOT NULL,
    email VARCHAR(254) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role VARCHAR(24) NOT NULL DEFAULT 'CUSTOMER',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_customer_accounts_name CHECK (btrim(full_name) <> ''),
    CONSTRAINT ck_customer_accounts_email_normalized CHECK (email = lower(btrim(email))),
    CONSTRAINT ck_customer_accounts_email_format CHECK (email ~* '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'),
    CONSTRAINT ck_customer_accounts_role CHECK (role = 'CUSTOMER')
);

CREATE UNIQUE INDEX uk_customer_accounts_email_normalized
    ON customer_accounts (lower(email));

CREATE TABLE customer_gadgets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL,
    category_id BIGINT NOT NULL,
    brand VARCHAR(100) NOT NULL,
    model VARCHAR(160) NOT NULL,
    purchase_date DATE,
    warranty_expiry_date DATE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_customer_gadgets_customer
        FOREIGN KEY (customer_id) REFERENCES customer_accounts (id) ON DELETE RESTRICT,
    CONSTRAINT fk_customer_gadgets_category
        FOREIGN KEY (category_id) REFERENCES device_categories (id) ON DELETE RESTRICT,
    CONSTRAINT ck_customer_gadgets_brand CHECK (btrim(brand) <> ''),
    CONSTRAINT ck_customer_gadgets_model CHECK (btrim(model) <> ''),
    CONSTRAINT ck_customer_gadgets_dates CHECK (
        purchase_date IS NULL OR warranty_expiry_date IS NULL OR warranty_expiry_date >= purchase_date
    )
);

CREATE INDEX idx_customer_gadgets_customer_created
    ON customer_gadgets (customer_id, created_at DESC, id DESC);

CREATE INDEX idx_customer_gadgets_category
    ON customer_gadgets (category_id);
