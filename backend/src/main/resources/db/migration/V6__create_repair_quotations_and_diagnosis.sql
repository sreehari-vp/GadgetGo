ALTER TABLE repair_bookings DROP CONSTRAINT IF EXISTS ck_repair_bookings_status;

ALTER TABLE repair_bookings ADD CONSTRAINT ck_repair_bookings_status
    CHECK (status IN ('PENDING_MATCH', 'OFFERED', 'ASSIGNED', 'DIAGNOSED', 'QUOTED', 'APPROVED', 'IN_PROGRESS', 'COMPLETED', 'NO_MATCH', 'CANCELLED'));

ALTER TABLE repair_bookings ADD CONSTRAINT ck_repair_bookings_assignment_consistency
    CHECK (
        (status IN ('ASSIGNED', 'DIAGNOSED', 'QUOTED', 'APPROVED', 'IN_PROGRESS', 'COMPLETED') AND assigned_technician_id IS NOT NULL) OR
        (status IN ('PENDING_MATCH', 'OFFERED', 'NO_MATCH', 'CANCELLED') AND assigned_technician_id IS NULL)
    );

ALTER TABLE repair_bookings ADD COLUMN IF NOT EXISTS repair_started_at TIMESTAMPTZ;
ALTER TABLE repair_bookings ADD COLUMN IF NOT EXISTS repair_completed_at TIMESTAMPTZ;

CREATE TABLE repair_quotations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL,
    technician_profile_id BIGINT NOT NULL,
    version INT NOT NULL DEFAULT 1,
    status VARCHAR(24) NOT NULL DEFAULT 'DRAFT',
    diagnosed_fault TEXT NOT NULL,
    proposed_repair TEXT NOT NULL,
    estimated_duration VARCHAR(100) NOT NULL,
    labour_charge NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    additional_charge NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    parts_total NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    total_amount NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    customer_notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    submitted_at TIMESTAMPTZ,
    responded_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_repair_quotations_booking
        FOREIGN KEY (booking_id) REFERENCES repair_bookings (id) ON DELETE CASCADE,
    CONSTRAINT fk_repair_quotations_technician
        FOREIGN KEY (technician_profile_id) REFERENCES technician_profiles (id) ON DELETE RESTRICT,
    CONSTRAINT ck_repair_quotations_status
        CHECK (status IN ('DRAFT', 'SUBMITTED', 'APPROVED', 'REJECTED', 'SUPERSEDED')),
    CONSTRAINT ck_repair_quotations_charges
        CHECK (labour_charge >= 0 AND additional_charge >= 0 AND parts_total >= 0 AND total_amount >= 0)
);

CREATE INDEX idx_repair_quotations_booking
    ON repair_quotations (booking_id, version DESC);

CREATE INDEX idx_repair_quotations_technician
    ON repair_quotations (technician_profile_id, status);

CREATE TABLE quotation_line_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quotation_id BIGINT NOT NULL,
    part_name VARCHAR(255) NOT NULL,
    quantity INT NOT NULL DEFAULT 1,
    unit_price NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    total_price NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    CONSTRAINT fk_quotation_line_items_quotation
        FOREIGN KEY (quotation_id) REFERENCES repair_quotations (id) ON DELETE CASCADE,
    CONSTRAINT ck_quotation_line_items_quantity
        CHECK (quantity > 0),
    CONSTRAINT ck_quotation_line_items_prices
        CHECK (unit_price >= 0 AND total_price >= 0)
);

CREATE INDEX idx_quotation_line_items_quotation
    ON quotation_line_items (quotation_id);

CREATE TABLE repair_status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL,
    from_status VARCHAR(24),
    to_status VARCHAR(24) NOT NULL,
    actor_role VARCHAR(24) NOT NULL,
    actor_id BIGINT,
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_repair_status_history_booking
        FOREIGN KEY (booking_id) REFERENCES repair_bookings (id) ON DELETE CASCADE
);

CREATE INDEX idx_repair_status_history_booking
    ON repair_status_history (booking_id, created_at ASC);
