CREATE TABLE repair_bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL,
    gadget_id BIGINT NOT NULL,
    repair_service_id BIGINT NOT NULL,
    service_mode VARCHAR(24) NOT NULL,
    problem_description TEXT NOT NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'PENDING_MATCH',
    assigned_technician_id BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_repair_bookings_customer
        FOREIGN KEY (customer_id) REFERENCES customer_accounts (id) ON DELETE RESTRICT,
    CONSTRAINT fk_repair_bookings_gadget
        FOREIGN KEY (gadget_id) REFERENCES customer_gadgets (id) ON DELETE RESTRICT,
    CONSTRAINT fk_repair_bookings_service
        FOREIGN KEY (repair_service_id) REFERENCES repair_services (id) ON DELETE RESTRICT,
    CONSTRAINT fk_repair_bookings_assigned_technician
        FOREIGN KEY (assigned_technician_id) REFERENCES technician_profiles (id) ON DELETE RESTRICT,
    CONSTRAINT ck_repair_bookings_service_mode
        CHECK (service_mode IN ('HOME_VISIT', 'REPAIR_CENTRE')),
    CONSTRAINT ck_repair_bookings_problem_description
        CHECK (btrim(problem_description) <> ''),
    CONSTRAINT ck_repair_bookings_status
        CHECK (status IN ('PENDING_MATCH', 'OFFERED', 'ASSIGNED', 'NO_MATCH', 'CANCELLED')),
    CONSTRAINT ck_repair_bookings_assignment_consistency
        CHECK (
            (status = 'ASSIGNED' AND assigned_technician_id IS NOT NULL) OR
            (status <> 'ASSIGNED' AND assigned_technician_id IS NULL)
        )
);

CREATE INDEX idx_repair_bookings_customer_created
    ON repair_bookings (customer_id, created_at DESC, id DESC);

CREATE INDEX idx_repair_bookings_status
    ON repair_bookings (status);

CREATE INDEX idx_repair_bookings_assigned_technician
    ON repair_bookings (assigned_technician_id);

CREATE TABLE assignment_offers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL,
    technician_profile_id BIGINT NOT NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'OFFERED',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    responded_at TIMESTAMPTZ,
    CONSTRAINT fk_assignment_offers_booking
        FOREIGN KEY (booking_id) REFERENCES repair_bookings (id) ON DELETE CASCADE,
    CONSTRAINT fk_assignment_offers_technician
        FOREIGN KEY (technician_profile_id) REFERENCES technician_profiles (id) ON DELETE RESTRICT,
    CONSTRAINT ck_assignment_offers_status
        CHECK (status IN ('OFFERED', 'ACCEPTED', 'REJECTED')),
    CONSTRAINT ck_assignment_offers_responded_at
        CHECK (
            (status = 'OFFERED' AND responded_at IS NULL) OR
            (status IN ('ACCEPTED', 'REJECTED') AND responded_at IS NOT NULL)
        ),
    CONSTRAINT uk_assignment_offers_booking_technician
        UNIQUE (booking_id, technician_profile_id)
);

CREATE INDEX idx_assignment_offers_technician_status
    ON assignment_offers (technician_profile_id, status);

CREATE INDEX idx_assignment_offers_booking_status
    ON assignment_offers (booking_id, status);

CREATE UNIQUE INDEX uk_assignment_offers_single_active_offer
    ON assignment_offers (booking_id)
    WHERE status = 'OFFERED';
